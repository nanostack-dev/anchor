package contract_test

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"testing"
)

const (
	readmePath    = "README.md"
	coverageBegin = "<!-- coverage:begin (generated by TestCoverageTable; run with -update) -->"
	coverageEnd   = "<!-- coverage:end -->"
)

// excludedPatterns are asserted only by exported flows that are not gate flows
// (testdata/gateflows/MANIFEST.md lists them).
var excludedPatterns = []struct{ status, code, reason string }{
	{"404", "WORKSPACE_NOT_FOUND", "flow `anchor: workspace` is tagged `anchor-retired` and failing; " +
		"the workspace routes were dropped (migration 000073)"},
	{"409", "WORKSPACE_NAME_DUPLICATE", "same retired flow"},
}

type patternUse struct {
	status, code string
	nodes        []string // "<flow>/<node>"
	goldens      []string
	skipped      []string
	messages     []string
}

// TestCoverageTable keeps the README's gate-assertion table in step with the
// flows, the goldens and the skip list.
func TestCoverageTable(t *testing.T) {
	patterns := map[string]*patternUse{}
	headerRows := map[string]int{}
	for _, path := range gateFlowPaths(t) {
		slug := strings.TrimSuffix(filepath.Base(path), ".json")
		flow, err := loadFlow(path)
		if err != nil {
			t.Fatal(err)
		}
		for _, node := range flow.Definition.Nodes {
			status, code, messages, headers := nodePattern(node)
			for _, h := range headers {
				headerRows[h]++
			}
			if status == "" && code == "" {
				continue
			}
			key := status + " " + code
			use := patterns[key]
			if use == nil {
				use = &patternUse{status: status, code: code}
				patterns[key] = use
			}
			ref := slug + "/" + node.ID
			use.nodes = append(use.nodes, ref)
			use.messages = append(use.messages, messages...)
			if _, skipped := gateSkips[ref]; skipped {
				use.skipped = append(use.skipped, ref)
				continue
			}
			golden := filepath.Join("gate", slug, safeName(node.ID)+".golden")
			if _, statErr := os.Stat(filepath.Join(goldenDir, golden)); statErr == nil {
				use.goldens = append(use.goldens, golden)
			}
		}
	}
	got := renderCoverage(patterns, headerRows)
	readme, err := os.ReadFile(readmePath)
	if err != nil {
		t.Fatal(err)
	}
	begin := strings.Index(string(readme), coverageBegin)
	end := strings.Index(string(readme), coverageEnd)
	if begin < 0 || end < begin {
		t.Fatalf("%s has no coverage markers", readmePath)
	}
	updated := string(readme[:begin]) + coverageBegin + "\n" + got + string(readme[end:])
	if updated == string(readme) {
		return
	}
	if *update {
		if writeErr := os.WriteFile(readmePath, []byte(updated), 0o600); writeErr != nil {
			t.Fatal(writeErr)
		}
		return
	}
	t.Errorf("%s coverage table is stale; run with -update:\n%s", readmePath, lineDiff(string(readme), updated))
}

// nodePattern returns the refusal a node asserts: an error status, the
// errors[0].code it expects, any message assertions and asserted headers.
func nodePattern(node flowNode) (string, string, []string, []string) {
	var status, code string
	var messages, headers []string
	for _, a := range node.Assertions {
		value := fmt.Sprint(a.OperatorData.Value)
		switch {
		case a.ExtractorType == "status_code" && a.OperatorType == "equals":
			if n, err := strconv.Atoi(value); err == nil && n >= 400 {
				status = value
			}
		case a.ExtractorType == "json_path" && strings.HasPrefix(a.ExtractorData.Path, "$.errors") &&
			strings.HasSuffix(a.ExtractorData.Path, ".code") && a.OperatorType == "equals":
			code = value
		case a.ExtractorType == "json_path" && strings.HasPrefix(a.ExtractorData.Path, "$.errors"):
			messages = append(messages, fmt.Sprintf("`%s %s %s`", a.ExtractorData.Path, a.OperatorType, value))
		case a.ExtractorType == "header":
			headers = append(headers, fmt.Sprintf("`%s` %s `%s`", a.ExtractorData.HeaderName, a.OperatorType, value))
		}
	}
	return status, code, messages, headers
}

func renderCoverage(patterns map[string]*patternUse, headerRows map[string]int) string {
	keys := make([]string, 0, len(patterns))
	for k := range patterns {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var b, missing, notRun strings.Builder
	covered, notCovered, nodes, nodesWithGolden := 0, 0, 0, 0
	b.WriteString("| Status | errors[0].code | Gate nodes | Golden case | Also asserted |\n")
	b.WriteString("|---|---|---:|---|---|\n")
	for _, k := range keys {
		use := patterns[k]
		nodes += len(use.nodes)
		nodesWithGolden += len(use.goldens)
		for _, ref := range use.nodes {
			slug, node, _ := strings.Cut(ref, "/")
			if !slices.Contains(use.goldens, filepath.Join("gate", slug, safeName(node)+".golden")) {
				fmt.Fprintf(&notRun, "- `%s` (`%s %s`)\n", ref, use.status, use.code)
			}
		}
		code := use.code
		if code == "" {
			code = "(status only)"
		}
		golden := "**not covered**"
		if len(use.goldens) > 0 {
			covered++
			golden = "`" + use.goldens[0] + "`"
			if len(use.goldens) > 1 {
				golden += fmt.Sprintf(" +%d", len(use.goldens)-1)
			}
		} else {
			notCovered++
			fmt.Fprintf(&missing, "- `%s %s` (%s): %s\n", use.status, code, strings.Join(use.nodes, ", "),
				missingReason(use))
		}
		also := strings.Join(dedupe(use.messages), "<br>")
		fmt.Fprintf(&b, "| %s | `%s` | %d | %s | %s |\n", use.status, code, len(use.nodes), golden, also)
	}
	for _, e := range excludedPatterns {
		notCovered++
		fmt.Fprintf(&missing, "- `%s %s`: %s\n", e.status, e.code, e.reason)
	}
	var out strings.Builder
	fmt.Fprintf(&out, "Distinct gate refusal patterns (status + `errors[0].code`): **%d covered, %d not covered**.\n\n",
		covered, notCovered)
	fmt.Fprintf(&out, "Gate refusal nodes: **%d of %d** have a golden.\n\n", nodesWithGolden, nodes)
	out.WriteString(b.String())
	out.WriteString("\nAsserted response headers (all covered by the goldens of the nodes that assert them):\n\n")
	headerKeys := make([]string, 0, len(headerRows))
	for k := range headerRows {
		headerKeys = append(headerKeys, k)
	}
	slices.Sort(headerKeys)
	for _, k := range headerKeys {
		fmt.Fprintf(&out, "- %s (%d)\n", k, headerRows[k])
	}
	out.WriteString("\nNot covered:\n\n")
	out.WriteString(missing.String())
	out.WriteString("\nRefusal nodes without a golden (skipped, or downstream of a skipped node):\n\n")
	out.WriteString(notRun.String())
	out.WriteString("\nSkipped gate nodes (assertions not enforced in-process):\n\n")
	skipKeys := make([]string, 0, len(gateSkips))
	for k := range gateSkips {
		skipKeys = append(skipKeys, k)
	}
	slices.Sort(skipKeys)
	for _, k := range skipKeys {
		fmt.Fprintf(&out, "- `%s`: %s\n", k, gateSkips[k])
	}
	return out.String()
}

func missingReason(use *patternUse) string {
	if len(use.skipped) > 0 {
		return gateSkips[use.skipped[0]]
	}
	return "no golden was written; the node did not run (an upstream node failed or was skipped)"
}

func dedupe(items []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, item := range items {
		if !seen[item] {
			seen[item] = true
			out = append(out, item)
		}
	}
	return out
}
